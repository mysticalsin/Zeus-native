import Foundation

/// Spacing for the revised settings mock-up. Section pages use these tokens.
public enum GlassSettingsMetrics {
    /// Height of a control row.
    public static let controlRow: Double = 52
    /// Height of the helper line under a control.
    public static let helperLine: Double = 16
    /// Padding inside the settings panel.
    public static let panelPadding: Double = 32
    /// Space between cards.
    public static let cardSpacing: Double = 28
}
