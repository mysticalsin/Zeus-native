import Foundation
import Testing
@testable import ZeusCore

/// A zero-width space stays on a parsed shortcut step. These tests name the blanks.
/// Linux `CharacterSet.whitespacesAndNewlines` treats U+200B as blank.
@Suite("Learned parse step box")
struct LearnedParseStepBoxTests {
    @Test func blankScalarsAreSpaceTabNewlineCarriageReturnAndNoBreakSpace() {
        #expect(LearnedParseStepBox.blankScalars == Set<Unicode.Scalar>([
            " ", "\t", "\n", "\r", "\u{00A0}",
        ]))
        #expect(LearnedParseStepBox.blankScalars.count == 5)
        #expect(LearnedParseStepBox.blankScalars.contains(" "))
        #expect(LearnedParseStepBox.blankScalars.contains("\t"))
        #expect(LearnedParseStepBox.blankScalars.contains("\n"))
        #expect(LearnedParseStepBox.blankScalars.contains("\r"))
        #expect(LearnedParseStepBox.blankScalars.contains("\u{00A0}"))
        #expect(!LearnedParseStepBox.blankScalars.contains("\u{200B}"))
        #expect(!LearnedParseStepBox.blankScalars.contains("\u{000B}"))
        #expect(!LearnedParseStepBox.blankScalars.contains("\u{3000}"))
    }

    @Test func aZeroWidthSpaceStaysOnTheTrimmedParseStep() {
        #expect(LearnedParseStepBox.trimmedParseStep("\u{200B}") == "\u{200B}")
        #expect(LearnedParseStepBox.trimmedParseStep(" \u{200B} ") == "\u{200B}")
        #expect(LearnedParseStepBox.trimmedParseStep("\t\u{200B}\n") == "\u{200B}")
        #expect(LearnedParseStepBox.trimmedParseStep("\u{200B}close") == "\u{200B}close")
        #expect(LearnedParseStepBox.trimmedParseStep("close\u{200B}") == "close\u{200B}")
        #expect(LearnedParseStepBox.trimmedParseStep(" \t\n\r\u{00A0}") == "")
        #expect(LearnedParseStepBox.trimmedParseStep("") == "")
        #expect(LearnedParseStepBox.trimmedParseStep("\u{000B}close") == "\u{000B}close")
        #expect(LearnedParseStepBox.trimmedParseStep("\u{3000}close") == "\u{3000}close")
        #expect(LearnedParseStepBox.trimmedParseStep(" \tclose\r\n") == "close")
        #expect(LearnedParseStepBox.trimmedParseStep("\u{00A0}close\u{00A0}") == "close")
        #expect(LearnedParseStepBox.trimmedParseStep("close") == "close")
        #expect(LearnedParseStepBox.trimmedParseStep("\u{200B}close Slack") == "\u{200B}close Slack")
        #expect(LearnedParseStepBox.trimmedParseStep("close Slack\u{200B}") == "close Slack\u{200B}")
        #expect(LearnedParseStepBox.trimmedParseStep("\nclose Slack") == "close Slack")
        #expect(LearnedParseStepBox.trimmedParseStep("\rclose Slack") == "close Slack")
    }

    @Test func aZeroWidthSpaceStaysOnAParsedStep() {
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack and \u{200B}open Notes")?.steps == ["close Slack", "\u{200B}open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\u{200B} and open Notes")?.steps == ["close Slack\u{200B}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack and \u{200B} and open Notes")?.steps == ["close Slack", "\u{200B}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack then \u{200B}open Notes")?.steps == ["close Slack", "\u{200B}open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close\u{200B}Slack")?.steps == ["close\u{200B}Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{000B}close Slack")?.steps == ["\u{000B}close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\u{000B} and open Notes")?.steps == ["close Slack\u{000B}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\u{000B}")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{000B}") == nil)
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{000B}do close Slack")?.steps == ["\u{000B}do close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack and \u{000B} and open Notes")?.steps == ["close Slack", "\u{000B}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack and \u{3000}open Notes")?.steps == ["close Slack", "\u{3000}open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\u{3000} and open Notes")?.steps == ["close Slack\u{3000}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus, close Slack and \u{200B}open Notes")?.steps == ["close Slack", "\u{200B}open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus, close Slack and \u{200B} and open Notes")?.steps == ["close Slack", "\u{200B}", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus, \u{000B}close Slack")?.steps == ["\u{000B}close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus, \u{000B}do close Slack")?.steps == ["\u{000B}do close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus, close Slack and \u{3000}open Notes")?.steps == ["close Slack", "\u{3000}open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack and \u{00A0}open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\r and open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \nclose Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\r")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{00A0}close Slack\u{00A0}")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{200B}close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack\u{200B}")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{200B}do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{200B}") == nil)
        #expect(NamedShortcutPhrase.parse("when i say focus do \u{3000}") == nil)
        #expect(NamedShortcutPhrase.parse("when i say focus do \n\t \u{00A0}") == nil)
        #expect(NamedShortcutPhrase.parse("when i say focus, \u{200B}do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus, \u{3000}do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus, \ndo close Slack")?.steps == ["do close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus\u{200B} do close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus\u{000B} do close Slack")?.phrase == "focus\u{000B}")
        #expect(NamedShortcutPhrase.parse("when i say focus\u{000B} do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus\u{3000} do close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus\n do close Slack")?.phrase == "focus\n")
        #expect(NamedShortcutPhrase.parse("when i say focus\r do close Slack")?.phrase == "focus\r")
        #expect(NamedShortcutPhrase.parse("when i say focus\u{200B}, close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus\u{000B}, close Slack")?.phrase == "focus\u{000B}")
        #expect(NamedShortcutPhrase.parse("when i say focus\u{3000}, close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus\n, close Slack")?.phrase == "focus\n")
        #expect(NamedShortcutPhrase.parse("when i say focus\r, close Slack")?.phrase == "focus\r")
        #expect(NamedShortcutPhrase.parse("when i say \u{00A0}focus mode do close Slack and open Notes")?.phrase == "focus mode")
        #expect(NamedShortcutPhrase.parse("when i say \u{00A0}focus mode do close Slack and open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("  when i say focus do close Slack  ")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("  when i say focus do close Slack  ")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("When I say focus mode do close Slack and open Notes")?.phrase == "focus mode")
        #expect(NamedShortcutPhrase.parse("When I say focus mode do close Slack and open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack then open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus do Do close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("when i say focus, close Slack")?.phrase == "focus")
        #expect(NamedShortcutPhrase.parse("when i say focus, close Slack")?.steps == ["close Slack"])
        #expect(NamedShortcutPhrase.parse("When I say focus mode, close Slack and open Notes")?.phrase == "focus mode")
        #expect(NamedShortcutPhrase.parse("When I say focus mode, close Slack and open Notes")?.steps == ["close Slack", "open Notes"])
        #expect(NamedShortcutPhrase.parse("when i say \u{200B}") == nil)
        #expect(NamedShortcutPhrase.parse("") == nil)
        #expect(NamedShortcutPhrase.parse("focus do close Slack") == nil)
    }
}
